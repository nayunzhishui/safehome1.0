def load(relative: str):
    return json.loads((ROOT / relative).read_text(encoding="utf-8"))


def add_heading(doc: Document, text: str, level: int, page_break: bool = False) -> None:
    paragraph = doc.add_heading(text, level=level)
    if page_break:
        paragraph.paragraph_format.page_break_before = True


def add_prose(doc: Document, *paragraphs: str) -> None:
    for text in paragraphs:
        paragraph = doc.add_paragraph(text)
        paragraph.paragraph_format.first_line_indent = Pt(21)
        paragraph.paragraph_format.keep_together = False


def git_rows() -> list[list[str]]:
    result = subprocess.run(
        ["git", "log", "--since=2026-06-20", "--pretty=format:%h|%ad|%s", "--date=short"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    rows = []
    for line in result.stdout.splitlines():
        commit, date, subject = line.split("|", 2)
        rows.append([date, commit, subject])
    return rows


