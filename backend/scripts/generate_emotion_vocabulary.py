"""Generate the mini-program copy of content/emotion_vocabulary.json.

The mini program cannot load content files at runtime, so the diary form reads this
generated module. Run after changing the vocabulary:

    python backend/scripts/generate_emotion_vocabulary.py
"""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "content" / "emotion_vocabulary.json"
MINIPROGRAM_OUTPUT = ROOT / "apps" / "miniprogram" / "utils" / "emotionVocabulary.generated.js"


def generate_miniprogram(vocabulary: dict) -> str:
    payload = json.dumps(vocabulary, ensure_ascii=False, indent=2)
    return (
        "// Generated by backend/scripts/generate_emotion_vocabulary.py from content/emotion_vocabulary.json.\n"
        f"const VOCABULARY = {payload};\n\n"
        "module.exports = { VOCABULARY };\n"
    )


def outputs() -> dict[Path, str]:
    vocabulary = json.loads(SOURCE.read_text(encoding="utf-8"))
    return {MINIPROGRAM_OUTPUT: generate_miniprogram(vocabulary)}


def main() -> None:
    for path, content in outputs().items():
        path.write_text(content, encoding="utf-8")
        print(f"generated {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
